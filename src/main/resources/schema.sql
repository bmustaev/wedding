-- Seating chart scoped to one admin — MariaDB has no table-valued SQL
-- function like Postgres, so this is a stored procedure returning a
-- result set instead of a view: CALL get_seating_chart_for_admin('...').
-- Defined further down (after the side/label columns exist below), not
-- here — the procedure body needs v_table_occupancy's "label" column,
-- which the HALL LAYOUT section below adds.
-- ---------------------------------------------------------------------

-- =====================================================================
-- HALL LAYOUT — bride/groom/head sides for seating_tables, plus which
-- side each admin belongs to. Appended as ALTER statements (not folded
-- into the CREATE TABLE blocks above) so this stays safely re-runnable
-- against a database that already has the original tables — every
-- ALTER here uses IF [NOT] EXISTS, a MariaDB extension supported since
-- 10.1.4/10.0.2, so re-running this on a database that's already been
-- migrated is a clean no-op rather than an error.
-- =====================================================================

-- Which side an admin belongs to. NULL for super_admin (not tied to a
-- side); required for a regular admin — enforced in the application
-- layer at admin-creation time, not by a NOT NULL here, since super_admin
-- genuinely has no side.
ALTER TABLE admins
    ADD COLUMN IF NOT EXISTS side VARCHAR(10) NULL CHECK (side IN ('bride', 'groom'))$$

-- seating_tables gains a side. table_number becomes nullable (the head
-- table isn't numbered) and its uniqueness becomes per-side instead of
-- global (both a "1B" and a "1D" table can coexist).
ALTER TABLE seating_tables
    ADD COLUMN IF NOT EXISTS side VARCHAR(10) NOT NULL DEFAULT 'bride' CHECK (side IN ('bride', 'groom', 'head'))$$

ALTER TABLE seating_tables MODIFY COLUMN table_number INT NULL$$

ALTER TABLE seating_tables DROP INDEX IF EXISTS uk_seating_tables_number$$

ALTER TABLE seating_tables ADD UNIQUE INDEX IF NOT EXISTS uk_seating_tables_side_number (side, table_number)$$

-- The original 8 generic tables (from before this feature existed) have
-- no meaningful side and don't fit the new model — clear them out ONCE
-- so data.sql can seed a proper head/bride/groom layout instead.
--
-- This must NOT run on every restart — schema.sql re-runs on every boot,
-- and admins will be creating/deleting their own tables through the app
-- from now on, so an unconditional DELETE here would silently wipe their
-- work on every subsequent restart. Guarded by a small migrations-applied
-- table so the cleanup fires exactly once, ever.

CREATE TABLE IF NOT EXISTS schema_migrations (
    migration_name  VARCHAR(100) NOT NULL PRIMARY KEY,
    applied_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci$$

DROP PROCEDURE IF EXISTS apply_hall_layout_migration$$

CREATE PROCEDURE apply_hall_layout_migration()
BEGIN
    IF NOT EXISTS (SELECT 1 FROM schema_migrations WHERE migration_name = 'hall_layout_v1') THEN
        DELETE FROM seating_tables;
        INSERT INTO schema_migrations (migration_name) VALUES ('hall_layout_v1');
    END IF;
END$$

CALL apply_hall_layout_migration()$$
DROP PROCEDURE IF EXISTS apply_hall_layout_migration$$

-- ---------------------------------------------------------------------
-- Views/procedures updated to carry side + a display label
-- ---------------------------------------------------------------------

CREATE OR REPLACE VIEW v_table_occupancy AS
SELECT
    st.id AS table_id,
    st.side,
    st.table_number,
    CASE
        WHEN st.side = 'head' THEN 'Head Table'
        WHEN st.side = 'bride' THEN CONCAT(st.table_number, 'D')
        WHEN st.side = 'groom' THEN CONCAT(st.table_number, 'B')
    END AS label,
    st.capacity,
    COALESCE(SUM(g.party_size), 0) AS seats_taken,
    st.capacity - COALESCE(SUM(g.party_size), 0) AS seats_left,
    COUNT(g.id) AS parties_seated
FROM seating_tables st
LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
GROUP BY st.id, st.side, st.table_number, st.capacity
ORDER BY st.side, st.table_number$$

DROP PROCEDURE IF EXISTS get_seating_chart_for_admin$$

CREATE PROCEDURE get_seating_chart_for_admin(IN p_admin_id CHAR(36))
BEGIN
    -- super_admin sees every guest by name, same as if every guest were
    -- its own — computed once here rather than repeating the subquery
    -- per row.
    DECLARE v_is_super_admin BOOLEAN DEFAULT FALSE;
    SELECT (role = 'super_admin') INTO v_is_super_admin FROM admins WHERE id = p_admin_id;

    SELECT
        st.id AS table_id,
        st.side,
        st.table_number,
        occ.label,
        st.capacity,
        occ.seats_left,
        g.id AS guest_id,
        CASE WHEN v_is_super_admin OR g.admin_id = p_admin_id
             THEN g.display_name
             ELSE CONCAT('Reserved (', g.party_size, ' seats)')
        END AS display_name,
        g.party_size,
        (v_is_super_admin OR g.admin_id = p_admin_id) AS is_own_guest
    FROM seating_tables st
    JOIN v_table_occupancy occ ON occ.table_id = st.id
    LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
    ORDER BY st.side, st.table_number, is_own_guest DESC, g.display_name;
END$$