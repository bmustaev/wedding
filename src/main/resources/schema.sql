-- ---------------------------------------------------------------------
-- Views/procedures updated to carry side + a display label
-- ---------------------------------------------------------------------

CREATE OR REPLACE VIEW v_table_occupancy AS
SELECT
    st.id AS table_id,
    st.hall,
    st.side,
    st.table_number,
    CASE
        WHEN st.side = 'head' THEN 'Head Table'
        WHEN st.side = 'bride' THEN CONCAT(st.table_number, 'D')
        WHEN st.side = 'groom' THEN CONCAT(st.table_number, 'B')
    END AS label,
    st.capacity,
    COALESCE(SUM(g.party_size), 0) AS seats_taken,
    st.capacity - COALESCE(SUM(g.party_size), 0) AS seats_left,
    COUNT(g.id) AS parties_seated
FROM seating_tables st
LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
GROUP BY st.id, st.hall, st.side, st.table_number, st.capacity
ORDER BY st.hall, st.side, st.table_number$$

DROP PROCEDURE IF EXISTS get_seating_chart_for_admin$$

CREATE PROCEDURE get_seating_chart_for_admin(IN p_admin_id CHAR(36))
BEGIN
    -- super_admin sees every guest by name, same as if every guest were
    -- its own; a hall admin (admins.hall set) likewise sees every guest
    -- its side has in its hall — mirrors AdminPrincipal.canManageGuest.
    -- Looked up once here rather than repeating the subquery per row.
    DECLARE v_is_super_admin BOOLEAN DEFAULT FALSE;
    DECLARE v_side VARCHAR(10) DEFAULT NULL;
    DECLARE v_hall VARCHAR(20) DEFAULT NULL;
    SELECT (role = 'super_admin'), side, hall INTO v_is_super_admin, v_side, v_hall
    FROM admins WHERE id = p_admin_id;

    SELECT
        st.id AS table_id,
        st.hall,
        st.side,
        st.table_number,
        occ.label,
        st.capacity,
        occ.seats_left,
        g.id AS guest_id,
        CASE WHEN v_is_super_admin OR g.admin_id = p_admin_id
                  OR (v_hall IS NOT NULL AND g.hall = v_hall AND ga.side = v_side)
             THEN g.display_name
             ELSE CONCAT('Reserved (', g.party_size, ' seats)')
        END AS display_name,
        CASE WHEN v_is_super_admin OR g.admin_id = p_admin_id
                  OR (v_hall IS NOT NULL AND g.hall = v_hall AND ga.side = v_side)
             THEN g.landing_slug
             ELSE NULL
        END AS landing_slug,
        g.party_size,
        (v_is_super_admin OR g.admin_id = p_admin_id
         OR (v_hall IS NOT NULL AND g.hall = v_hall AND ga.side = v_side)) AS is_own_guest
    FROM seating_tables st
    JOIN v_table_occupancy occ ON occ.table_id = st.id
    LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
    LEFT JOIN admins ga ON ga.id = g.admin_id
    ORDER BY st.hall, st.side, st.table_number, is_own_guest DESC, g.display_name;
END$$

-- ---------------------------------------------------------------------
-- Guests triggers: a guest may only sit at a table in their own hall,
-- and the table must have room (check_table_capacity, defined above).
-- ---------------------------------------------------------------------

DROP PROCEDURE IF EXISTS check_table_hall$$

CREATE PROCEDURE check_table_hall(
    IN p_table_id CHAR(36),
    IN p_hall VARCHAR(20)
)
BEGIN
    DECLARE v_table_hall VARCHAR(20);

    IF p_table_id IS NOT NULL THEN
        SELECT hall INTO v_table_hall FROM seating_tables WHERE id = p_table_id;

        IF v_table_hall <> p_hall THEN
            SIGNAL SQLSTATE '45000'
                SET MESSAGE_TEXT = 'This table is in a different hall than the guest is invited to';
        END IF;
    END IF;
END$$

