CREATE OR REPLACE VIEW v_table_occupancy AS
SELECT
    st.id                                          AS table_id,
    st.table_number,
    st.capacity,
    COALESCE(SUM(g.party_size), 0)                 AS seats_taken,
    st.capacity - COALESCE(SUM(g.party_size), 0)    AS seats_left,
    COUNT(g.id)                                     AS parties_seated
FROM seating_tables st
LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
GROUP BY st.id, st.table_number, st.capacity
ORDER BY st.table_number$$

CREATE OR REPLACE VIEW v_guest_media_allowance AS
SELECT
    g.id AS guest_id,
    g.display_name,
    SUM(CASE WHEN gm.media_type = 'photo' THEN 1 ELSE 0 END)      AS photos_used,
    15 - SUM(CASE WHEN gm.media_type = 'photo' THEN 1 ELSE 0 END) AS photos_remaining,
    SUM(CASE WHEN gm.media_type = 'video' THEN 1 ELSE 0 END)      AS videos_used,
    4 - SUM(CASE WHEN gm.media_type = 'video' THEN 1 ELSE 0 END)  AS videos_remaining
FROM guests g
LEFT JOIN guest_media gm ON gm.guest_id = g.id
WHERE g.is_deleted = 0
GROUP BY g.id, g.display_name$$

CREATE OR REPLACE VIEW v_table_seating_super_admin AS
SELECT
    st.table_number,
    st.capacity,
    occ.seats_left,
    g.id           AS guest_id,
    g.display_name,
    g.party_size,
    a.username     AS owning_admin
FROM seating_tables st
JOIN v_table_occupancy occ ON occ.table_id = st.id
LEFT JOIN guests g ON g.table_id = st.id AND g.is_deleted = 0
LEFT JOIN admins a ON a.id = g.admin_id
ORDER BY st.table_number, g.display_name$$

