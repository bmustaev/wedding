DROP TRIGGER IF EXISTS trg_guest_media_limit$$

CREATE TRIGGER trg_guest_media_limit
BEFORE INSERT ON guest_media
FOR EACH ROW
BEGIN
    DECLARE current_count INT;
    DECLARE max_allowed INT;

    SELECT COUNT(*) INTO current_count
    FROM guest_media
    WHERE guest_id = NEW.guest_id AND media_type = NEW.media_type;

    IF NEW.media_type = 'photo' THEN
        SET max_allowed = 15;
    ELSE
        SET max_allowed = 4;
    END IF;

    IF current_count >= max_allowed THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Guest already has the maximum allowed uploads for this media type';
    END IF;
END$$

-- Table-capacity check factored into a procedure so both the INSERT and
-- UPDATE triggers on guests can share it (MariaDB has no "BEFORE INSERT
-- OR UPDATE" combined trigger the way Postgres does).
DROP PROCEDURE IF EXISTS check_table_capacity$$

CREATE PROCEDURE check_table_capacity(
    IN p_table_id CHAR(36),
    IN p_guest_id CHAR(36),
    IN p_party_size INT
)
BEGIN
    DECLARE v_capacity INT;
    DECLARE v_seats_taken INT;

    IF p_table_id IS NOT NULL THEN
        SELECT capacity INTO v_capacity FROM seating_tables WHERE id = p_table_id;

        SELECT COALESCE(SUM(party_size), 0) INTO v_seats_taken
        FROM guests
        WHERE table_id = p_table_id
          AND is_deleted = 0
          AND id <> p_guest_id;

        IF v_seats_taken + p_party_size > v_capacity THEN
            SIGNAL SQLSTATE '45000'
                SET MESSAGE_TEXT = 'This table does not have enough seats left for this guest';
        END IF;
    END IF;
END$$

