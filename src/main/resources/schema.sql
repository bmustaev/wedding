-- =====================================================================
-- Wedding Invitation Platform — schema.sql (MariaDB)
--
-- Spring Boot auto-runs this file against the `wedding` database on
-- startup (see application.yml: spring.sql.init.mode=always). It must
-- be idempotent-safe to re-run, so every statement uses IF NOT EXISTS
-- where MariaDB supports it.
--
-- STATEMENT SEPARATOR: this file uses a custom two-character separator (not ";") as the boundary
-- between statements — see application.yml: spring.sql.init.separator.
-- That's required because trigger/procedure bodies below contain their
-- own internal ";" characters (one per inner statement in the BEGIN...END
-- block), and Spring Boot's script runner executes this file directly
-- over JDBC — it has no idea what a MySQL-CLI "DELIMITER" command is
-- (that's a client-only directive, not real SQL), so DELIMITER must
-- never appear in this file. Using the custom separator as the one global
-- boundary for the *entire* file (not just the trigger sections) avoids
-- needing it at all.
--
-- Design notes carried over from the original PostgreSQL version of
-- this schema, adapted for MariaDB:
--   - UUID primary keys are generated by Hibernate in the app
--     (GenerationType.UUID), not by the database, so columns are plain
--     CHAR(36) with no DEFAULT expression needed.
--   - created_at/updated_at are set by Hibernate (@CreationTimestamp /
--     @UpdateTimestamp), so DEFAULT/ON UPDATE clauses here are only a
--     safety net, not the source of truth.
--   - The four enum-like columns (role, media_type, moderation_status,
--     status) are VARCHAR + CHECK rather than a dedicated ENUM type —
--     matches the AttributeConverter mapping in the Java entities and
--     is easier to alter later than MariaDB's ENUM column type.
--   - Postgres arrays aren't available; guests.group_members is stored
--     as comma-separated TEXT and converted in the Java entity layer.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Fix the database's own default collation before anything else runs.
-- Table columns get their collation explicitly (COLLATE=utf8mb4_unicode_ci
-- on every CREATE TABLE below), but stored procedure parameters without
-- an explicit COLLATE clause inherit the DATABASE's default collation at
-- the moment CREATE PROCEDURE runs — not the connection's
-- collation_connection setting (that's a separate mechanism; see
-- application.yml's sessionVariables comment). If the database itself
-- was ever created without this exact COLLATE clause — e.g. just
-- CREATE DATABASE wedding CHARACTER SET utf8mb4; — MariaDB silently
-- falls back to its own server default (often utf8mb4_general_ci),
-- causing "Illegal mix of collations" errors on any procedure that
-- compares a parameter against a table column. No database name is
-- given below — ALTER DATABASE with no name applies to whichever
-- database the current connection is already using, so this is safe
-- regardless of what DB_NAME is configured to.
-- ---------------------------------------------------------------------

ALTER DATABASE CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci$$

