-- =====================================================================
-- HALL LAYOUT — bride/groom/head sides for seating_tables, plus which
-- side each admin belongs to. Appended as ALTER statements (not folded
-- into the CREATE TABLE blocks above) so this stays safely re-runnable
-- against a database that already has the original tables — every
-- ALTER here uses IF [NOT] EXISTS, a MariaDB extension supported since
-- 10.1.4/10.0.2, so re-running this on a database that's already been
-- migrated is a clean no-op rather than an error.
-- =====================================================================

-- Which side an admin belongs to. NULL for super_admin (not tied to a
